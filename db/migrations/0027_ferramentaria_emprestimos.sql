-- NAUTILUS · Ferramentaria e Inventário, fase B: terceirizadas, empréstimos, assinaturas e devoluções.
-- Emitir o empréstimo abate o estoque na hora (movimento "emprestimo"). Na devolução, o que volta em bom
-- estado entra de novo no estoque (movimento "devolucao"); ferramenta danificada ou perdida e material
-- consumido não voltam. Nada é apagado; quantidades nunca passam do emprestado; assinaturas são gravadas uma vez.
SET LOCAL lock_timeout='15s';

CREATE TABLE IF NOT EXISTS tool_contractors (
  id text PRIMARY KEY,
  name text NOT NULL CHECK (length(trim(name)) BETWEEN 1 AND 120),
  active smallint NOT NULL DEFAULT 1 CHECK (active IN (0,1)),
  created_at text NOT NULL,
  updated_at text NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS tool_contractors_name_key ON tool_contractors (lower(trim(name)));

CREATE TABLE IF NOT EXISTS tool_contractor_people (
  id text PRIMARY KEY,
  contractor_id text NOT NULL REFERENCES tool_contractors(id),
  name text NOT NULL CHECK (length(trim(name)) BETWEEN 1 AND 120),
  active smallint NOT NULL DEFAULT 1 CHECK (active IN (0,1)),
  created_at text NOT NULL,
  updated_at text NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS tool_contractor_people_name_key ON tool_contractor_people (contractor_id, lower(trim(name)));

CREATE TABLE IF NOT EXISTS tool_loans (
  id text PRIMARY KEY,
  number integer GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  contractor_id text NOT NULL REFERENCES tool_contractors(id),
  contractor_name text NOT NULL,
  contractor_person text NOT NULL CHECK (length(trim(contractor_person)) BETWEEN 1 AND 120),
  ocp_name text NOT NULL CHECK (length(trim(ocp_name)) BETWEEN 1 AND 120),
  purpose text NOT NULL CHECK (length(trim(purpose)) BETWEEN 1 AND 300),
  expected_return text NOT NULL CHECK (expected_return ~ '^\d{4}-\d{2}-\d{2}$'),
  status text NOT NULL DEFAULT 'emitido' CHECK (status IN ('emitido','parcial','encerrado','cancelado')),
  ocp_signature text CHECK (ocp_signature IS NULL OR (ocp_signature LIKE 'data:image/png;base64,%' AND length(ocp_signature) <= 400000)),
  contractor_signature text CHECK (contractor_signature IS NULL OR (contractor_signature LIKE 'data:image/png;base64,%' AND length(contractor_signature) <= 400000)),
  signed_at text,
  signed_by_name text,
  issued_at text NOT NULL,
  issued_by text NOT NULL REFERENCES members(id),
  issued_by_name text NOT NULL,
  closed_at text,
  closed_by_name text,
  cancelled_at text,
  cancelled_by_name text,
  cancel_reason text,
  create_key text NOT NULL UNIQUE,
  version integer NOT NULL DEFAULT 0,
  CONSTRAINT tool_loan_signed CHECK ((ocp_signature IS NULL) = (contractor_signature IS NULL) AND (ocp_signature IS NULL) = (signed_at IS NULL)),
  CONSTRAINT tool_loan_cancel CHECK ((status = 'cancelado') = (cancelled_at IS NOT NULL) AND (status <> 'cancelado' OR length(trim(coalesce(cancel_reason,''))) > 0))
);
CREATE INDEX IF NOT EXISTS idx_tool_loans_contractor ON tool_loans (contractor_id, status);
CREATE INDEX IF NOT EXISTS idx_tool_loans_status ON tool_loans (status, expected_return);

CREATE TABLE IF NOT EXISTS tool_loan_lines (
  id text PRIMARY KEY,
  loan_id text NOT NULL REFERENCES tool_loans(id),
  item_id text NOT NULL REFERENCES tool_items(id),
  item_name text NOT NULL,
  item_kind text NOT NULL CHECK (item_kind IN ('ferramenta','material')),
  unit_abbr text NOT NULL,
  qty_out_milli bigint NOT NULL CHECK (qty_out_milli > 0),
  qty_returned_milli bigint NOT NULL DEFAULT 0 CHECK (qty_returned_milli >= 0),
  qty_damaged_milli bigint NOT NULL DEFAULT 0 CHECK (qty_damaged_milli >= 0),
  qty_lost_milli bigint NOT NULL DEFAULT 0 CHECK (qty_lost_milli >= 0),
  qty_consumed_milli bigint NOT NULL DEFAULT 0 CHECK (qty_consumed_milli >= 0),
  UNIQUE (loan_id, item_id),
  CONSTRAINT tool_loan_line_total CHECK (qty_returned_milli + qty_damaged_milli + qty_lost_milli + qty_consumed_milli <= qty_out_milli),
  CONSTRAINT tool_loan_line_kind CHECK ((item_kind = 'ferramenta' AND qty_consumed_milli = 0) OR (item_kind = 'material' AND qty_damaged_milli = 0 AND qty_lost_milli = 0))
);
CREATE INDEX IF NOT EXISTS idx_tool_loan_lines_loan ON tool_loan_lines (loan_id);
CREATE INDEX IF NOT EXISTS idx_tool_loan_lines_item ON tool_loan_lines (item_id);

CREATE TABLE IF NOT EXISTS tool_loan_returns (
  id text PRIMARY KEY,
  loan_id text NOT NULL REFERENCES tool_loans(id),
  number integer NOT NULL CHECK (number >= 1),
  note text CHECK (note IS NULL OR length(note) <= 500),
  closes_loan smallint NOT NULL DEFAULT 0 CHECK (closes_loan IN (0,1)),
  ocp_signature text CHECK (ocp_signature IS NULL OR (ocp_signature LIKE 'data:image/png;base64,%' AND length(ocp_signature) <= 400000)),
  contractor_signature text CHECK (contractor_signature IS NULL OR (contractor_signature LIKE 'data:image/png;base64,%' AND length(contractor_signature) <= 400000)),
  signed_at text,
  created_at text NOT NULL,
  created_by text NOT NULL REFERENCES members(id),
  created_by_name text NOT NULL,
  create_key text NOT NULL UNIQUE,
  UNIQUE (loan_id, number),
  CONSTRAINT tool_return_signed CHECK ((ocp_signature IS NULL) = (contractor_signature IS NULL) AND (ocp_signature IS NULL) = (signed_at IS NULL))
);

CREATE TABLE IF NOT EXISTS tool_loan_return_lines (
  id text PRIMARY KEY,
  return_id text NOT NULL REFERENCES tool_loan_returns(id),
  line_id text NOT NULL REFERENCES tool_loan_lines(id),
  returned_milli bigint NOT NULL DEFAULT 0 CHECK (returned_milli >= 0),
  damaged_milli bigint NOT NULL DEFAULT 0 CHECK (damaged_milli >= 0),
  lost_milli bigint NOT NULL DEFAULT 0 CHECK (lost_milli >= 0),
  consumed_milli bigint NOT NULL DEFAULT 0 CHECK (consumed_milli >= 0),
  UNIQUE (return_id, line_id),
  CONSTRAINT tool_return_line_any CHECK (returned_milli + damaged_milli + lost_milli + consumed_milli > 0)
);

-- Termo assinado em papel (escaneado): PDF, JPG ou PNG de até 4 MB, no próprio banco.
CREATE TABLE IF NOT EXISTS tool_loan_files (
  id text PRIMARY KEY,
  loan_id text NOT NULL REFERENCES tool_loans(id),
  return_id text REFERENCES tool_loan_returns(id),
  file_name text NOT NULL,
  content_type text NOT NULL CHECK (content_type IN ('application/pdf','image/jpeg','image/png')),
  size_bytes integer NOT NULL CHECK (size_bytes BETWEEN 1 AND 4194304),
  content bytea NOT NULL,
  created_at text NOT NULL,
  created_by text NOT NULL REFERENCES members(id),
  created_by_name text NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_tool_loan_files_loan ON tool_loan_files (loan_id);

-- Empréstimo: identificação fixa, assinatura gravada uma vez, situação só avança.
CREATE OR REPLACE FUNCTION nautilus_tool_loan_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.id <> OLD.id OR NEW.number <> OLD.number OR NEW.contractor_id <> OLD.contractor_id OR NEW.contractor_person <> OLD.contractor_person
     OR NEW.issued_at <> OLD.issued_at OR NEW.issued_by <> OLD.issued_by OR NEW.create_key <> OLD.create_key
     OR NEW.purpose <> OLD.purpose OR NEW.ocp_name <> OLD.ocp_name OR NEW.expected_return <> OLD.expected_return THEN
    RAISE EXCEPTION 'Empréstimo emitido não pode ser alterado';
  END IF;
  IF OLD.ocp_signature IS NOT NULL AND (NEW.ocp_signature IS DISTINCT FROM OLD.ocp_signature OR NEW.contractor_signature IS DISTINCT FROM OLD.contractor_signature) THEN
    RAISE EXCEPTION 'Assinatura do empréstimo já registrada';
  END IF;
  IF NEW.status <> OLD.status AND NOT (
      (OLD.status = 'emitido' AND NEW.status IN ('parcial','encerrado','cancelado'))
      OR (OLD.status = 'parcial' AND NEW.status = 'encerrado')) THEN
    RAISE EXCEPTION 'Situação do empréstimo não pode passar de % para %', OLD.status, NEW.status;
  END IF;
  RETURN NEW;
END $$;
CREATE OR REPLACE TRIGGER tool_loan_guard BEFORE UPDATE ON tool_loans FOR EACH ROW EXECUTE FUNCTION nautilus_tool_loan_guard();

-- Linha: só os contadores de devolução mudam, e só crescem.
CREATE OR REPLACE FUNCTION nautilus_tool_loan_line_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.id <> OLD.id OR NEW.loan_id <> OLD.loan_id OR NEW.item_id <> OLD.item_id OR NEW.qty_out_milli <> OLD.qty_out_milli
     OR NEW.item_name <> OLD.item_name OR NEW.item_kind <> OLD.item_kind OR NEW.unit_abbr <> OLD.unit_abbr THEN
    RAISE EXCEPTION 'Item do empréstimo não pode ser alterado';
  END IF;
  IF NEW.qty_returned_milli < OLD.qty_returned_milli OR NEW.qty_damaged_milli < OLD.qty_damaged_milli
     OR NEW.qty_lost_milli < OLD.qty_lost_milli OR NEW.qty_consumed_milli < OLD.qty_consumed_milli THEN
    RAISE EXCEPTION 'Devolução registrada não pode ser desfeita';
  END IF;
  RETURN NEW;
END $$;
CREATE OR REPLACE TRIGGER tool_loan_line_guard BEFORE UPDATE ON tool_loan_lines FOR EACH ROW EXECUTE FUNCTION nautilus_tool_loan_line_guard();

-- Devolução: só a assinatura em tela pode ser gravada depois, uma vez.
CREATE OR REPLACE FUNCTION nautilus_tool_return_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.id <> OLD.id OR NEW.loan_id <> OLD.loan_id OR NEW.number <> OLD.number OR NEW.closes_loan <> OLD.closes_loan
     OR NEW.note IS DISTINCT FROM OLD.note OR NEW.created_at <> OLD.created_at OR NEW.created_by <> OLD.created_by OR NEW.create_key <> OLD.create_key
     OR (OLD.ocp_signature IS NOT NULL AND (NEW.ocp_signature IS DISTINCT FROM OLD.ocp_signature OR NEW.contractor_signature IS DISTINCT FROM OLD.contractor_signature)) THEN
    RAISE EXCEPTION 'Devolução registrada não pode ser alterada';
  END IF;
  RETURN NEW;
END $$;
CREATE OR REPLACE TRIGGER tool_return_guard BEFORE UPDATE ON tool_loan_returns FOR EACH ROW EXECUTE FUNCTION nautilus_tool_return_guard();

CREATE OR REPLACE FUNCTION nautilus_tool_record_immutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'Registro do empréstimo não pode ser alterado nem apagado'; END $$;
CREATE OR REPLACE TRIGGER tool_return_lines_immutable BEFORE UPDATE OR DELETE ON tool_loan_return_lines FOR EACH ROW EXECUTE FUNCTION nautilus_tool_record_immutable();
CREATE OR REPLACE TRIGGER tool_loan_files_immutable BEFORE UPDATE OR DELETE ON tool_loan_files FOR EACH ROW EXECUTE FUNCTION nautilus_tool_record_immutable();

CREATE OR REPLACE TRIGGER tool_contractors_no_delete BEFORE DELETE ON tool_contractors FOR EACH ROW EXECUTE FUNCTION nautilus_tool_no_delete();
CREATE OR REPLACE TRIGGER tool_contractor_people_no_delete BEFORE DELETE ON tool_contractor_people FOR EACH ROW EXECUTE FUNCTION nautilus_tool_no_delete();
CREATE OR REPLACE TRIGGER tool_loans_no_delete BEFORE DELETE ON tool_loans FOR EACH ROW EXECUTE FUNCTION nautilus_tool_record_immutable();
CREATE OR REPLACE TRIGGER tool_loan_lines_no_delete BEFORE DELETE ON tool_loan_lines FOR EACH ROW EXECUTE FUNCTION nautilus_tool_record_immutable();
CREATE OR REPLACE TRIGGER tool_loan_returns_no_delete BEFORE DELETE ON tool_loan_returns FOR EACH ROW EXECUTE FUNCTION nautilus_tool_record_immutable();

DO $$ DECLARE t text; r text; BEGIN
  FOREACH t IN ARRAY ARRAY['tool_contractors','tool_contractor_people','tool_loans','tool_loan_lines','tool_loan_returns','tool_loan_return_lines','tool_loan_files'] LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    FOREACH r IN ARRAY ARRAY['anon','authenticated'] LOOP
      IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = r) THEN EXECUTE format('REVOKE ALL ON TABLE %I FROM %I', t, r); END IF;
    END LOOP;
  END LOOP;
END $$;

DO $$ DECLARE f regprocedure; BEGIN
  FOR f IN SELECT p.oid::regprocedure FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
    WHERE n.nspname = current_schema() AND p.proname LIKE 'nautilus\_%' LOOP
    EXECUTE format('ALTER FUNCTION %s SET search_path TO %I', f, current_schema());
  END LOOP;
END $$;
